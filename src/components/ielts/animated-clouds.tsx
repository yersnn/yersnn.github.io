export function AnimatedClouds({ containerWidth = "100vw" }: { containerWidth?: string }) {
  return (
    <div
      className="pointer-events-none absolute inset-0 overflow-hidden"
      style={{ filter: "blur(2px)" }}
    >
      <style>{`
        @keyframes cloud-drift-overlay {
          0%   { transform: translateX(var(--start)) scale(var(--scale)); }
          100% { transform: translateX(var(--end)) scale(var(--scale)); }
        }
      `}</style>
      {instances.map((c, i) => {
        const w = c.tpl.width * c.scale;
        return (
          <div
            key={i}
            style={{
              position: "absolute",
              top: c.top,
              left: c.left,
              width: c.tpl.width,
              height: c.tpl.height,
              transformOrigin: "top left",
              ["--start" as string]: `${-c.left - w - 50}px`,
              ["--end" as string]: `calc(${containerWidth} - ${c.left}px + 50px)`,
              ["--scale" as string]: `${c.scale}`,
              animation: `cloud-drift-overlay ${c.duration}s linear ${c.delay}s infinite`,
              willChange: "transform",
            }}
          >
            <svg
              className="block size-full"
              fill="none"
              preserveAspectRatio="none"
              viewBox={c.tpl.viewBox}
            >
              <g>
                {c.tpl.paths.map((p, j) => (
                  <path
                    key={j}
                    d={p.d}
                    fill={p.fill}
                    fillOpacity={p.fillOpacity}
                  />
                ))}
              </g>
            </svg>
          </div>
        );
      })}
    </div>
  );
}
